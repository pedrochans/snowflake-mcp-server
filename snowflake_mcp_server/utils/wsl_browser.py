"""Make the Snowflake login page open in the Windows browser under WSL.

The native core of snowflake-connector-python 5.x ignores ``BROWSER`` on WSL
and launches ``explorer.exe <url>`` found on ``PATH``. For long login URLs
Windows Explorer opens a File Explorer window (Documents) instead of the
browser, so the SSO / OAuth login never completes and connect times out.

On WSL we prepend a private directory to this process' ``PATH`` holding an
``explorer.exe`` shim: URLs go to ``wslview`` (or ``rundll32`` url handler),
anything else is forwarded to the real Explorer. Nothing outside the MCP
process is changed.
"""

import os
import shutil
import stat
import tempfile
from pathlib import Path
from typing import Optional

_SHIM_NAME = "explorer.exe"
_WSL_INTEROP = Path("/proc/sys/fs/binfmt_misc/WSLInterop")
_PROC_VERSION = Path("/proc/version")

_shim_dir: Optional[str] = None


def is_wsl() -> bool:
    """Return True when running inside WSL."""
    if _WSL_INTEROP.exists():
        return True
    try:
        return "microsoft" in _PROC_VERSION.read_text().lower()
    except OSError:
        return False


def _shim_script(real_explorer: Optional[str]) -> str:
    fallback = f'exec "{real_explorer}" "$@"' if real_explorer else "exit 1"
    return f"""#!/bin/sh
# Generated by snowflake-mcp-server: open login URLs in the Windows browser.
case "$1" in
  http://*|https://*)
    if command -v wslview >/dev/null 2>&1; then
      exec wslview -s "$1"
    fi
    exec rundll32.exe url.dll,FileProtocolHandler "$1"
    ;;
esac
{fallback}
"""


def install_wsl_browser_shim() -> Optional[str]:
    """Install the ``explorer.exe`` shim on WSL and return its directory.

    Idempotent; returns None (and changes nothing) outside WSL.
    """
    global _shim_dir
    if not is_wsl():
        return None
    if _shim_dir is not None:
        return _shim_dir

    path = os.environ.get("PATH", "")
    real_explorer = shutil.which(_SHIM_NAME, path=path)
    shim_dir = tempfile.mkdtemp(prefix="snowflake-mcp-browser-")
    shim = Path(shim_dir) / _SHIM_NAME
    shim.write_text(_shim_script(real_explorer))
    shim.chmod(stat.S_IRWXU)
    os.environ["PATH"] = shim_dir + os.pathsep + path if path else shim_dir
    _shim_dir = shim_dir
    return shim_dir
